class Command(BaseCommand):
    help = ('Наполняет базу демо-контентом: языки, курсы по JavaScript (Python наполняется отдельной '
            'командой seed_python_course), несколько примеров кода и заданий на урок, достижения.')

    def handle(self, *args, **options):
        languages_by_slug = {}
        for lang_data in LANGUAGES:
            lang, _ = ProgrammingLanguage.objects.get_or_create(
                slug=lang_data['slug'],
                defaults={
                    'name': lang_data['name'],
                    'icon': lang_data['icon'],
                    'description': lang_data['description'],
                },
            )
            languages_by_slug[lang_data['slug']] = lang

        lesson_count = 0
        example_count = 0
        task_count = 0

        for lang_slug, levels in COURSE_CONTENT.items():
            language = languages_by_slug[lang_slug]
            for level in LEVEL_ORDER:
                if level not in levels:
                    continue
                lessons_data = levels[level]
                course, _ = Course.objects.get_or_create(
                    language=language,
                    level=level,
                    defaults={
                        'title': f'{language.name}: {LEVEL_TITLES[level]}',
                        'description': f'{LEVEL_TITLES[level]} уровень курса по {language.name}.',
                        'order': LEVEL_ORDER.index(level) + 1,
                    },
                )
                for lesson_order, lesson_data in enumerate(lessons_data, start=1):
                    lesson, created = Lesson.objects.update_or_create(
                        course=course,
                        order=lesson_order,
                        defaults={
                            'title': lesson_data['title'],
                            'theory': lesson_data['theory'],
                            'xp_reward': 10,
                        },
                    )
                    lesson_count += 1

                    # Пересоздаём примеры кода и задания, чтобы повторный запуск seed_demo
                    # обновлял контент, а не плодил дубликаты.
                    lesson.code_examples.all().delete()
                    for ex_order, example in enumerate(lesson_data['examples'], start=1):
                        CodeExample.objects.create(
                            lesson=lesson,
                            title=example['title'],
                            code=example['code'],
                            explanation=example.get('explanation', ''),
                            order=ex_order,
                        )
                        example_count += 1

                    lesson.tasks.all().delete()
                    for task_order, task in enumerate(lesson_data['tasks'], start=1):
                        Task.objects.create(
                            lesson=lesson,
                            task_type=Task.TYPE_TEST,
                            question=task['question'],
                            hint=task.get('hint', ''),
                            correct_answer=task['answer'],
                            xp_reward=5,
                            order=task_order,
                        )
                        task_count += 1

        for code, title, desc, icon in ACHIEVEMENTS:
            Achievement.objects.get_or_create(code=code, defaults={'title': title, 'description': desc, 'icon': icon})

        self.stdout.write(self.style.SUCCESS(
            f'Загружено: {len(LANGUAGES)} языка(ов), {lesson_count} уроков (JavaScript; Python — через seed_python_course), '
            f'{example_count} примеров кода, {task_count} заданий, {len(ACHIEVEMENTS)} достижений.'
        ))
